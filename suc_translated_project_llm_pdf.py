def translate_markdown(text):
    print("[*] 2. جاري الترجمة إلى العربية (يرجى الانتظار)...")
    translator = GoogleTranslator(source="en", target="ar")
    lines = text.split("\n")
    translated_lines = []

    img_pattern = re.compile(r"!\[(.*?)\]\((.*?)\)")

    for line in lines:
        stripped = line.strip()
        if not stripped:
            translated_lines.append("")
            continue

        # الحفاظ على الصور
        img_match = img_pattern.match(stripped)
        if img_match:
            alt, src = img_match.groups()
            translated_lines.append(f"![{alt}]({src})")
            continue

        # ترجمة الفقرات العادية
        if len(stripped) > 2:
            ar_line = safe_translate(stripped, translator)
            translated_lines.append(ar_line)
            time.sleep(0.2)  # مهلة لتفادي حظر جوجل
        else:
            translated_lines.append(line)

    return "\n".join(translated_lines)

