def clean_gutenberg_garbage(text):
    """حذف شوائب طباعة المتصفح وتذييلات جوتنبرج"""
    cleaned_lines = []
    for line in text.splitlines():
        # استبعاد الأسطر المشوهة وسجلات الطباعة
        if re.search(r'\d{2}:\d{2}\s*,\s*\d+/\d+/\d+', line): # تاريخ ووقت
            continue
        if re.search(r'of\s+\d+\s+\d+', line): # ترقيم صفحات متصفح
            continue
        if "pg23989" in line or "gutenberg.org/cache" in line:
            continue
        # استبعاد الرموز المكسورة مثل: 2S ee $ Hs; LS
        if re.match(r'^[A-Za-z0-9\s\$\;\,\(\)\=\*\-\\\"]{15,}$', line.strip()) and " " in line and len(line.split()) > 4:
            words = line.strip().split()
            if all(len(w) <= 3 for w in words): # كلمات عشوائية من حرف أو حرفين
                continue
        cleaned_lines.append(line)
    return "\n".join(cleaned_lines)

def safe_translate(text, translator):
    """ترجمة نص مع محاولة إعادة المحاولة في حال الخطأ"""
    if not text.strip():
        return ""
    for attempt in range(3):
        try:
            return translator.translate(text)
        except Exception:
            time.sleep(1)
    return text  # إذا فشل يعيد النص الأصلي

