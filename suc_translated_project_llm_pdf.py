def step2_translate_large_book(md_text, cache_file):
    """
    يترجم الكتاب فقرة بفقرة، مع حفظ دوري يمنع ضياع التقدم
    لو انقطع الاتصال أو أغلقت الجلسة.
    """
    print("\n[*] 2. جاري تجهيز النص والترجمة بنظام الحفظ التلقائي للكتب الكبيرة...")

    # عزل علامات الصور
    images_list = []
    def stash_image(match):
        idx = len(images_list)
        images_list.append(match.group(0))
        return f"\n\n__IMG_TOKEN_{idx}__\n\n"

    protected_text = re.sub(r"!\[.*?\]\(file://.*?\)", stash_image, md_text)
    paragraphs = [p.strip() for p in protected_text.split("\n\n") if p.strip()]

    # استعادة التقدم المحفوظ من قبل
    cache_data = {}
    if os.path.exists(cache_file):
        try:
            with open(cache_file, "r", encoding="utf-8") as f:
                cache_data = json.load(f)
            print(f"[i] تم العثور على تقدم محفوظ مسبقاً: سيتم استكمال العمل من الفقرة ({len(cache_data)}).")
        except Exception:
            cache_data = {}

    total = len(paragraphs)
    translated_paras = []

    for idx, p in enumerate(paragraphs):
        str_idx = str(idx)

        # إذا كانت الفقرة مترجمة مسبقاً في ملف الـ Checkpoint نتجاوزها فوراً
        if str_idx in cache_data:
            translated_paras.append(cache_data[str_idx])
            continue

        if "__IMG_TOKEN_" in p:
            result = p
        else:
            # تقسيم الفقرة إلى جمل بناءً على علامات الترقيم
            raw_sents = [s.strip() for s in re.split(r'(?<=[.!?\n])\s+', p) if s.strip()]
            if raw_sents:
                result = translate_sentences_batch(raw_sents, batch_size=8)
            else:
                result = p

        translated_paras.append(result)
        cache_data[str_idx] = result

        # حفظ التقدم كل 10 فقرات وتنظيف الذاكرة
        if (idx + 1) % 10 == 0 or (idx + 1) == total:
            with open(cache_file, "w", encoding="utf-8") as f:
                json.dump(cache_data, f, ensure_ascii=False)

            progress_pct = ((idx + 1) / total) * 100
            print(f"    - تقدم الترجمة: {idx+1}/{total} فقرة ({progress_pct:.1f}%) [محفوظ تلقائياً]")

            # تفريغ ذاكرة الرام وكارت الشاشة لمنع انهيار الجلسة
            if DEVICE == "cuda":
                torch.cuda.empty_cache()
            gc.collect()

    # إعادة دمج وسوم الصور في أماكنها الصحيحة
    full_text = "\n\n".join(translated_paras)
    for i, img in enumerate(images_list):
        full_text = full_text.replace(f"__IMG_TOKEN_{i}__", img)

    return full_text


