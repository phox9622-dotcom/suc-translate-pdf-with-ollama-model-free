def translate_sentences_safe(sentences, batch_size=8):
    """ترجمة على دفعات صغيرة لتفادي CUDA Out of Memory"""
    translated_all = []
    for i in range(0, len(sentences), batch_size):
        batch = sentences[i:i + batch_size]
        try:
            inputs = tokenizer(batch, return_tensors="pt", padding=True, truncation=True, max_length=512).to(device)
            with torch.no_grad():
                outputs = model.generate(**inputs)
            translated_all.extend(tokenizer.batch_decode(outputs, skip_special_tokens=True))
        except Exception:
            translated_all.extend(batch)
    return " ".join(translated_all)

def step2_translate_with_cache(md_text, cache_file):
    """ترجمة تدعم الاستئناف التلقائي وحفظ التقدم للكتب الكبيرة"""
    print("[*] 2. جاري تجهيز النص والترجمة (مع الحفظ التلقائي)...")

    # عزل الصور
    images_list = []
    def stash_image(match):
        idx = len(images_list)
        images_list.append(match.group(0))
        return f"\n\n__IMG_TOKEN_{idx}__\n\n"

    protected_text = re.sub(r"!\[.*?\]\(file://.*?\)", stash_image, md_text)
    paragraphs = [p.strip() for p in protected_text.split("\n\n") if p.strip()]

    # تحميل التقدم السابق إن وجد
    cache_data = {}
    if os.path.exists(cache_file):
        try:
            with open(cache_file, "r", encoding="utf-8") as f:
                cache_data = json.load(f)
            print(f"[i] تم العثور على تقدم محفوظ مسبقاً: تم إنجاز {len(cache_data)} فقرة.")
        except Exception:
            cache_data = {}

    total = len(paragraphs)
    translated_paras = []

    for idx, p in enumerate(paragraphs):
        str_idx = str(idx)

        # استرجاع الفقرة من الذاكرة إذا كانت مترجمة مسبقاً
        if str_idx in cache_data:
            translated_paras.append(cache_data[str_idx])
            continue

        if "__IMG_TOKEN_" in p:
            result = p
        else:
            raw_sents = [s.strip() for s in re.split(r'(?<=[.!?\n])\s+', p) if s.strip()]
            if raw_sents:
                result = translate_sentences_safe(raw_sents)
            else:
                result = p

        translated_paras.append(result)
        cache_data[str_idx] = result

        # حفظ التقدم كل 10 فقرات
        if (idx + 1) % 10 == 0 or (idx + 1) == total:
            with open(cache_file, "w", encoding="utf-8") as f:
                json.dump(cache_data, f, ensure_ascii=False)
            print(f"    - تم إنجاز {idx+1}/{total} فقرة (تم الحفظ التلقائي)")

            # تنظيف الذاكرة
            if device == "cuda":
                torch.cuda.empty_cache()
            gc.collect()

    # إعادة دمج الصور
    full_text = "\n\n".join(translated_paras)
    for i, img in enumerate(images_list):
        full_text = full_text.replace(f"__IMG_TOKEN_{i}__", img)

    return full_text

