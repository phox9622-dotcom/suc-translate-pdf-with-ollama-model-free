print("[*] جاري تحميل النموذج والمجزئ اللغوي (Helsinki-NLP/opus-mt-en-ar)...")
model_name = "Helsinki-NLP/opus-mt-en-ar"

device = "cuda" if torch.cuda.is_available() else "cpu"
tokenizer = AutoTokenizer.from_pretrained(model_name)
model = AutoModelForSeq2SeqLM.from_pretrained(model_name).to(device)
print(f"[+] تم تجهيز النموذج بنجاح وهو يعمل على: {device.upper()}")

def step1_extract(pdf_path, output_dir):
    """استخراج Markdown والصور وحفظها بمسارات مطلقة"""
    os.makedirs(output_dir, exist_ok=True)
    images_dir = os.path.abspath(os.path.join(output_dir, "images"))
    os.makedirs(images_dir, exist_ok=True)

    print(f"[*] 1. جاري استخراج النص والصور من {pdf_path}...")
    md_text = pymupdf4llm.to_markdown(
        pdf_path,
        write_images=True,
        image_path=images_dir,
        image_format="png"
    )

    extracted_images = os.listdir(images_dir)
    print(f"[+] تم استخراج {len(extracted_images)} صورة إلى مجلد: {images_dir}")

    # تحويل مسارات الصور إلى مسارات نظام مطلقة
    def fix_img_path(match):
        alt = match.group(1)
        src = match.group(2)
        filename = os.path.basename(src)
        abs_path = os.path.join(images_dir, filename)
        return f"![{alt}](file://{abs_path})"

    md_text = re.sub(r"!\[(.*?)\]\((.*?)\)", fix_img_path, md_text)
    return md_text

def translate_batch(text_chunk):
    """ترجمة الفقرة عبر تقسيمها لجمل ومعالجتها دفعة واحدة عبر الموديل"""
    if not text_chunk.strip():
        return ""

    # تقسيم الفقرة إلى جمل
    raw_sentences = re.split(r'(?<=[.!?\n])\s+', text_chunk)
    sentences = [s.strip() for s in raw_sentences if s.strip()]
    if not sentences:
        return ""

    try:
        # معالجة الجمل معاً على كارت الشاشة أو المعالج
        inputs = tokenizer(sentences, return_tensors="pt", padding=True, truncation=True, max_length=512).to(device)
        with torch.no_grad():
            translated_tokens = model.generate(**inputs)
        translated_sentences = tokenizer.batch_decode(translated_tokens, skip_special_tokens=True)
        return " ".join(translated_sentences)
    except Exception as e:
        print(f"[!] خطأ أثناء الترجمة: {e}")
        return text_chunk

def step2_translate(md_text):
    """حماية الصور وترجمة كتل النصوص"""
    print("[*] 2. جاري ترجمة النص إلى العربية بالذكاء الاصطناعي...")

    # عزل وسوم الصور حتى لا تتشوه أثناء الترجمة
    images_list = []
    def stash_image(match):
        idx = len(images_list)
        images_list.append(match.group(0))
        return f"\n\n__IMG_TOKEN_{idx}__\n\n"

    protected_text = re.sub(r"!\[.*?\]\(file://.*?\)", stash_image, md_text)
    paragraphs = protected_text.split("\n\n")
    translated_paras = []

    total = len(paragraphs)
    for i, p in enumerate(paragraphs):
        p_strip = p.strip()
        if not p_strip:
            continue

        # إذا كان السطر صورة لا نترجمه
        if "__IMG_TOKEN_" in p_strip:
            translated_paras.append(p_strip)
        else:
            ar_text = translate_batch(p_strip)
            translated_paras.append(ar_text)

        if (i + 1) % 10 == 0 or (i + 1) == total:
            print(f"    - تقدم الترجمة: {i+1}/{total} مقطع")

    # استرجاع وسوم الصور وروابطها الأصلية
    full_translated = "\n\n".join(translated_paras)
    for idx, img_tag in enumerate(images_list):
        full_translated = full_translated.replace(f"__IMG_TOKEN_{idx}__", img_tag)

    return full_translated

