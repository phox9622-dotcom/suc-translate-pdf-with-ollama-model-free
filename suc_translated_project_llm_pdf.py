def step2_translate(md_text):
    """ترجمة كتل النصوص مع عزل الصور وحمايتها"""
    print("[*] 2. جاري تجهيز النص وحماية وسوم الصور...")

    # عزل علامات الصور وحفظها في مصفوفة
    images_list = []
    def stash_image(match):
        idx = len(images_list)
        images_list.append(match.group(0))
        return f"\n\n__IMG_TOKEN_{idx}__\n\n"

    # استبدال كل صورة برمز مؤقت
    protected_text = re.sub(r"!\[.*?\]\(file://.*?\)", stash_image, md_text)

    # تقسيم النص إلى فقرات مجمعة
    paragraphs = protected_text.split("\n\n")
    chunks = []
    current_chunk = ""

    for p in paragraphs:
        if "__IMG_TOKEN_" in p:
            if current_chunk.strip():
                chunks.append(current_chunk.strip())
                current_chunk = ""
            chunks.append(p.strip())
        else:
            if len(current_chunk) + len(p) < 1800:
                current_chunk += p + "\n\n"
            else:
                chunks.append(current_chunk.strip())
                current_chunk = p + "\n\n"

    if current_chunk.strip():
        chunks.append(current_chunk.strip())

    print(f"[*] جاري ترجمة {len(chunks)} مقطع إلى العربية...")
    translator = GoogleTranslator(source="en", target="ar")
    translated_chunks = []

    for i, chunk in enumerate(chunks):
        if chunk.startswith("__IMG_TOKEN_"):
            translated_chunks.append(chunk)
            continue

        success = False
        for attempt in range(4):
            try:
                # محاولة الترجمة
                res = translator.translate(chunk)
                if res and any('\u0600' <= char <= '\u06FF' for char in res):
                    translated_chunks.append(res)
                    success = True
                    break
            except Exception as e:
                print(f"[!] خطأ اتصال في المقطع {i+1}، إعادة المحاولة بعد ثوانٍ...")
                time.sleep(3)

        if not success:
            raise RuntimeError(
                f"فشلت الترجمة عند المقطع {i+1}! خدمة جوجل حظرت الطلبات مؤقتاً. "
                "يرجى الانتظار 5 دقائق والمحاولة مرة أخرى أو استخدام VPN."
            )

        print(f"    - تم إنجاز {i+1}/{len(chunks)}")
        time.sleep(1.2)  # مهلة ضرورية جداً لحماية الـ IP من حظر جوجل

    # دمج النص وإرجاع الصور إلى أماكنها الأصلية
    full_translated = "\n\n".join(translated_chunks)
    for idx, img_tag in enumerate(images_list):
        full_translated = full_translated.replace(f"__IMG_TOKEN_{idx}__", img_tag)

    return full_translated

