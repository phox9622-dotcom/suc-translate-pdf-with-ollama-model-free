# ==========================================
# 1. استخراج النص والصور بنظام الحماية ضد أخطاء OCR
# ==========================================
def step1_extract(pdf_path, output_dir):
    """
    استخراج Markdown والصور وحفظها بمسارات مطلقة،
    مع وجود نظام بديل (Fallback) في حال فشل الـ Layout Parser.
    """
    os.makedirs(output_dir, exist_ok=True)
    images_dir = os.path.abspath(os.path.join(output_dir, "images"))
    os.makedirs(images_dir, exist_ok=True)

    print(f"\n[*] 1. استخراج المحتوى والصور من: {pdf_path}...")

    md_text = ""
    # المحاولة الأولى: عبر pymupdf4llm بدون OCR لتجنب مشاكل RapidOCR
    try:
        md_text = pymupdf4llm.to_markdown(
            pdf_path,
            write_images=True,
            image_path=images_dir,
            image_format="png",
            use_ocr=False
        )
    except Exception as e:
        print(f"[!] تنبيه: تعذر الاستخراج عبر الموزع المتقدم ({e})، جاري التبديل للمستخرج المباشر Failsafe...")

        # المحاولة البديلة: استخراج مباشر عبر fitz (مستقر 100% ولا يتعطل أبداً)
        doc = fitz.open(pdf_path)
        chunks = []
        img_idx = 0

        for pno in range(len(doc)):
            page = doc[pno]

            # استخراج صور الصفحة
            for img_info in page.get_images(full=True):
                xref = img_info[0]
                base_img = doc.extract_image(xref)
                img_bytes = base_img["image"]
                img_ext = base_img["ext"]
                img_name = f"page_{pno+1}_img_{img_idx}.{img_ext}"
                img_path = os.path.join(images_dir, img_name)

                with open(img_path, "wb") as f_img:
                    f_img.write(img_bytes)

                chunks.append(f"![image](file://{img_path})")
                img_idx += 1

            # استخراج النص
            page_text = page.get_text("text").strip()
            if page_text:
                chunks.append(page_text)

        md_text = "\n\n".join(chunks)

    # توحيد مسارات الصور إلى صيغة مسار مطلق file://
    def fix_img_path(match):
        alt = match.group(1)
        src = match.group(2)
        if src.startswith("file://"):
            return match.group(0)
        filename = os.path.basename(src)
        abs_path = os.path.join(images_dir, filename)
        return f"![{alt}](file://{abs_path})"

    md_text = re.sub(r"!\[(.*?)\]\((.*?)\)", fix_img_path, md_text)

    extracted_imgs = os.listdir(images_dir)
    print(f"[+] تم استخراج النص وحفظ {len(extracted_imgs)} صورة في مجلد: {images_dir}")
    return md_text


