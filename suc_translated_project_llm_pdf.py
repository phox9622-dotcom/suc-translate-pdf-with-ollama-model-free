def translate_markdown_text(text, chunk_size=3500):
    """
    2. ترجمة نص Markdown إلى العربية مع الحفاظ على علامات الصور والروابط
    """
    translator = GoogleTranslator(source="auto", target="ar")
    lines = text.split("\n")
    translated_lines = []

    print("[*] جاري الترجمة إلى اللغة العربية...")

    # نمط regex لاكتشاف الصور: ![alt](path)
    img_pattern = re.compile(r"!\[(.*?)\]\((.*?)\)")

    buffer = ""

    def flush_buffer(buf):
        if not buf.strip():
            return ""
        try:
            return translator.translate(buf)
        except Exception as e:
            print(f"[!] خطأ أثناء ترجمة مقطع: {e}")
            return buf

    for line in lines:
        stripped = line.strip()

        # إذا كان السطر صورة، نحافظ على مسار الصورة كما هو ونترجم الوصف فقط
        img_match = img_pattern.match(stripped)
        if img_match:
            # ترجمة ما تم تجميعه مسبقاً
            if buffer:
                translated_lines.append(flush_buffer(buffer))
                buffer = ""

            alt_text, img_src = img_match.groups()
            translated_alt = translator.translate(alt_text) if alt_text else ""
            translated_lines.append(f"![{translated_alt}]({img_src})")
            continue

        # إذا كان السطر كود برمجي أو فارغ
        if stripped.startswith("```") or stripped.startswith("---"):
            if buffer:
                translated_lines.append(flush_buffer(buffer))
                buffer = ""
            translated_lines.append(line)
            continue

        # تجميع الأسطر لتقليل عدد طلبات الترجمة وتسريع العملية
        if len(buffer) + len(line) < chunk_size:
            buffer += line + "\n"
        else:
            translated_lines.append(flush_buffer(buffer))
            buffer = line + "\n"

    if buffer:
        translated_lines.append(flush_buffer(buffer))

    return "\n".join(translated_lines)

