# 2. الترجمة الآمنة على دفعات صغيرة لتفادي انهيار الذاكرة
# ==========================================
def translate_sentences_batch(sentences, batch_size=8):
    """ترجمة مجموعة جمل كدفعة واحدة (Batch) لحماية كارت الشاشة وتسريع الأداء"""
    translated_all = []
    for i in range(0, len(sentences), batch_size):
        batch = sentences[i:i + batch_size]
        try:
            inputs = tokenizer(batch, return_tensors="pt", padding=True, truncation=True, max_length=512).to(DEVICE)
            with torch.no_grad():
                outputs = model.generate(**inputs)
            decoded = tokenizer.batch_decode(outputs, skip_special_tokens=True)
            translated_all.extend(decoded)
        except Exception as e:
            # في حال حدوث أي خطأ في جملة ما، نحتفظ بالنص بدلاً من توقف البرنامج
            translated_all.extend(batch)
    return " ".join(translated_all)


